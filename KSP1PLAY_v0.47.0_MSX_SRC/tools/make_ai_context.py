#!/usr/bin/env python3
"""Create a compact, self-contained KSP1PLAY handoff for a fresh AI context."""
from __future__ import annotations
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'build'/'KSP1PLAY_AI_CONTEXT.md'
DOCS=[
 'START_HERE.md',
 'docs/ARCHITECTURE.md',
 'docs/MEMORY_MAP.md',
 'docs/OVERLAY_ABI.md',
 'docs/RUNTIME_FLOWS.md',
 'docs/KSP_STRUCTURES.md',
 'docs/CHANGE_GUIDE.md',
 'docs/ROUTINE_CONTRACTS.md',
 'docs/TESTING.md',
 'docs/NOP_POLICY.md',
 'docs/PROJECT_STATUS.md',
]
ABI=[
 'src/include/memory_map.inc','src/include/ksp_format.inc','src/include/ui_constants.inc',
 'src/include/menu_abi.inc','src/include/recon_abi.inc','src/include/service_abi.inc',
 'src/include/service_runtime_abi.inc','src/include/hvar_abi.inc','src/include/hvar_format.inc',
 'src/include/ui_p3_abi.inc','src/include/kspos_abi.inc','src/include/kspos_runtime_abi.inc',
 'src/include/image_format.inc','src/include/player_abi.inc','src/include/platform.inc',
]
manifest=(ROOT/'src/KSPPLAYER.asm').read_text()
modules=re.findall(r'include\s+"([^"]+\.asm)"',manifest,re.I)
parts=['# KSP1PLAY v0.47.0 — AI context', '',
       '> Generated by `tools/make_ai_context.py`. Use this as the first attachment/text for a clean context.', '',
       '## Hard constraints', '',
       '- Preserve exact fixed binary hashes unless the requested change intentionally changes behavior/layout.',
       '- Normal PLAY must remain free of disk/FAT/BDOS work.',
       '- Treat host-image addresses and runtime addresses as different address spaces.',
       '- Use ABI symbols for cross-runtime calls/state; do not add unexplained numeric addresses.',
       '- Preserve KSPMENU jump-table addresses and cleanup/mapper/audio invariants.', '',
       '## Active player module order', '']
for i,m in enumerate(modules,1): parts.append(f'{i}. `src/{m}`')
parts += ['', '---', '']
for rel in DOCS:
    p=ROOT/rel
    if p.exists():
        parts += [f'<!-- {rel} -->', p.read_text().strip(), '', '---', '']
parts += ['# ABI and format definitions', '']
for rel in ABI:
    p=ROOT/rel
    if not p.exists(): continue
    parts += [f'## `{rel}`', '', '```asm', p.read_text().rstrip(), '```', '']
parts += ['# Working rule for the next context','',
          'Inspect only the source modules relevant to the requested change. Run `python3 verify_source.py` after edits. '
          'If an exact hash changes unexpectedly, treat that as a regression before doing further refactoring.', '']
OUT.parent.mkdir(exist_ok=True)
OUT.write_text('\n'.join(parts),encoding='utf-8')
print(f'generated {OUT} ({OUT.stat().st_size} bytes)')
