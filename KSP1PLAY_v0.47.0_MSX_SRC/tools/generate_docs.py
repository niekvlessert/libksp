#!/usr/bin/env python3
"""Generate symbol and module-call documentation from the current build/source."""
from __future__ import annotations
import re
from collections import defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'src'; BUILD=ROOT/'build'; DOCS=ROOT/'docs'
LABEL_RE=re.compile(r'^([A-Za-z_.$][\w.$]*):\s*$',re.M)
CALL_RE=re.compile(r'^\s*call\s+([A-Za-z_.$][\w.$]*)\b',re.I|re.M)


def sym_file(path:Path)->dict[str,int]:
    out={}
    if not path.exists(): return out
    for line in path.read_text(errors='ignore').splitlines():
        m=re.match(r'\s*([A-Za-z_.$][\w.$]*)\s*=\s*0x([0-9A-Fa-f]+)',line)
        if m: out[m.group(1).lower()]=int(m.group(2),16)
    return out


def manifest_modules()->list[Path]:
    text=(SRC/'KSPPLAYER.asm').read_text()
    files=[]
    for inc in re.findall(r'include\s+"([^"]+\.asm)"',text,re.I):
        p=SRC/inc
        if p.exists(): files.append(p)
    return files

player_files=manifest_modules()
menu_file=SRC/'ui/KSPMENU.asm'
recon_file=SRC/'runtime/RECON_RUNTIME.asm'
boot_files=sorted((SRC/'boot').glob('*.asm'))
all_files=[]
for p in player_files+[menu_file,recon_file]+boot_files:
    if p not in all_files: all_files.append(p)

player_sym=sym_file(BUILD/'KSPPLAYER.sym')
menu_sym=sym_file(BUILD/'KSPMENU.sym')
recon_sym=sym_file(BUILD/'RECON_RUNTIME.sym')

# Label ownership for module dependencies.
owner={}
labels_by_file={}
for p in all_files:
    labels=LABEL_RE.findall(p.read_text(errors='ignore'))
    labels_by_file[p]=labels
    for label in labels: owner.setdefault(label.lower(),p)

# Symbol index.
lines=['# Symbol index','',
       'Generated by `tools/generate_docs.py`. Addresses are taken from the current build when available.','']
for p in all_files:
    rel=p.relative_to(ROOT)
    labels=labels_by_file[p]
    if not labels: continue
    if p==menu_file: sm=menu_sym
    elif p==recon_file: sm=recon_sym
    elif p in player_files: sm=player_sym
    else: sm={}
    lines += [f'## `{rel}`','', '| Address | Symbol |','|---:|---|']
    for label in labels:
        addr=sm.get(label.lower())
        a=f'`{addr:04X}h`' if addr is not None else '—'
        lines.append(f'| {a} | `{label}` |')
    lines.append('')
(DOCS/'SYMBOL_INDEX.md').write_text('\n'.join(lines)+'\n')

# Cross-module direct CALL dependencies.
deps=defaultdict(lambda: defaultdict(set))
for p in player_files:
    text=p.read_text(errors='ignore')
    for target in CALL_RE.findall(text):
        q=owner.get(target.lower())
        if q and q!=p:
            deps[p][q].add(target)

lines=['# Call graph','',
       'Generated from direct named `CALL` instructions plus a curated view of the main runtime flows.','',
       '## Primary flow','', '```text',
       'start',
       '  -> init_application_defaults',
       '  -> get_mapper_api',
       '  -> capture_original_pages',
       '  -> kspos_detect_and_prepare',
       '  -> ui_application',
       '       -> ui_menu / ui_load_pack',
       '       -> ui_install_selected_track',
       '       -> ui_play_screen',
       '            -> wait_vblank_without_keyclick',
       '            -> call_play',
       '            -> playback action dispatch',
       '```','',
       '## Track installation','', '```text',
       'ui_install_selected_track',
       '  -> select_track',
       '  -> ui_prepare_selected_engine',
       '  -> install_current_track',
       '       -> page-materialization ABI as required',
       '       -> patch_engine_gateways',
       '       -> prepare_engine_page2',
       '       -> call_init',
       '```','',
       '## Direct cross-module CALLs','']
for p in player_files:
    if p not in deps: continue
    lines += [f'### `{p.relative_to(ROOT)}`','']
    for q,targets in sorted(deps[p].items(),key=lambda x:str(x[0])):
        t=', '.join(f'`{x}`' for x in sorted(targets,key=str.lower))
        lines.append(f'- → `{q.relative_to(ROOT)}`: {t}')
    lines.append('')
(DOCS/'CALL_GRAPH.md').write_text('\n'.join(lines)+'\n')
print(f'generated {DOCS/"SYMBOL_INDEX.md"}')
print(f'generated {DOCS/"CALL_GRAPH.md"}')
